    _cached: ListedColormap | None = None

    @classmethod
    def colormap(cls) -> ListedColormap:
        """Returns the phase colormap, building and registering it on first call."""
        if cls._cached is None:
            alpha       = np.full(len(cls.R), 255)
            rgba        = np.column_stack([cls.R, cls.G, cls.B, alpha]) / 255.0
            cls._cached = ListedColormap(rgba, name=cls.NAME)

            if cls.NAME not in matplotlib.colormaps:
                matplotlib.colormaps.register(cls._cached, name=cls.NAME)

        return cls._cached
